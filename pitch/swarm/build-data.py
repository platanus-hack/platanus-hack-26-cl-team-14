# Build data.js (agents, messages) and prs.js from the raw Discord and GitHub exports in raw/.
# Story time = minutes since 2026-11-20 00:00 Chile (UTC-3). Phases, milestones and quotes stay hand-written in story.js.
import json, re
from datetime import datetime, timezone, timedelta

HERE = __file__.rsplit('/', 1)[0]
ORIGIN = datetime(2026, 11, 20, 3, 0, tzinfo=timezone.utc)
LOGINS = {'v4rgas': 'juan', 'emersoftware': 'emerson', 'BrunoFarfan': 'bruno', 'kiwivolador': 'francisco', 'vicentematus': 'vicente'}
MIN_MESSAGES = 3

def minutes(iso):
    return round((datetime.fromisoformat(iso.replace('Z', '+00:00')) - ORIGIN) / timedelta(minutes=1), 1)

discord = json.load(open(f'{HERE}/raw/discord.json'))
agents, by_message = {}, {}
for m in discord['messages']:
    match = re.match(r'^(.*?) \((.+?)@(.+?)\)$', m['author'] or '')
    if not match:
        continue
    name, left, right = match.groups()
    human = LOGINS.get(left) or LOGINS.get(right)
    if not human:
        continue
    key = f'{name}@{human}'
    a = agents.setdefault(key, {'name': name, 'human': human, 'from': minutes(m['t']), 'to': minutes(m['t']), 'n': 0})
    a['to'] = minutes(m['t'])
    a['n'] += 1
    by_message[m['id']] = (key, m)

kept = {k: a for k, a in agents.items() if a['n'] >= MIN_MESSAGES}
messages = []
for key, m in by_message.values():
    link = re.search(r'discord\.com/channels/\d+/\d+/(\d+)', m['text'] or '')
    target = by_message.get(m['reply_to'] or (link and link.group(1)))
    if key in kept and target and target[0] in kept and target[0] != key:
        messages.append([minutes(m['t']), key, target[0]])

end = max(a['to'] for a in agents.values())
rows = [[k, a['human'], a['from'], max(a['to'], a['from'] + 10), a['name'], a['n']] for k, a in sorted(kept.items(), key=lambda kv: kv[1]['from'])]
with open(f'{HERE}/data.js', 'w') as out:
    out.write('// Generated by build-data.py from raw/discord.json. Do not edit by hand.\n')
    out.write(f'window.END_DATA = {end};\n')
    out.write('// [id, human, from, to, name, messages]\n')
    out.write('window.AGENT_ROWS = ' + json.dumps(rows, ensure_ascii=False) + ';\n')
    out.write('// [time, from agent id, to agent id] replies between kept agents\n')
    out.write('window.MESSAGES = ' + json.dumps(messages) + ';\n')
    out.write('// Story minute of every Discord message (humans and agents), sorted.\n')
    out.write('window.DISCORD_TIMES = ' + json.dumps(sorted(round(minutes(m['t'])) for m in discord['messages'])) + ';\n')

prs = json.load(open(f'{HERE}/raw/prs.json'))
with open(f'{HERE}/prs.js', 'w') as out:
    out.write('// Generated by build-data.py from raw/prs.json. [number, created, merged, closed, author]\n')
    out.write('window.PRS = ' + json.dumps([[p['number'], minutes(p['createdAt']), p['mergedAt'] and minutes(p['mergedAt']), p['closedAt'] and minutes(p['closedAt']), p['author']] for p in prs]) + ';\n')

print(len(agents), 'agents,', len(kept), 'kept,', len(messages), 'replies, end', end, ', prs', len(prs))
